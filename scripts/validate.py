"""Numerical validation of the pricing engines against results known in closed form.

Checks
  1. rBergomi martingale: E[S_T] = 1 (r = 0) for rough H and strong correlation.
  2. rBergomi variance swap: fair strike equals xi0 for a flat forward variance curve.
  3. rBergomi ATM skew power law: |d sigma / dk| ~ T^(H - 1/2); regress log skew on log T, H_est = slope + 1/2.
  4. Rough Heston characteristic function at H close to 1/2 versus the closed-form classical Heston one.
  5. Rough Heston call prices: positive and decreasing in strike.

Writes results/validation.json and renders the README Validation block.

    python scripts/validate.py           # run checks, rewrite README block
    python scripts/validate.py --check   # exit 1 if README is out of date with results/
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from rough_vol.models.rbergomi import RBergomiParams, implied_vol_surface, simulate_paths  # noqa: E402
from rough_vol.models.rfheston import RHestonParams, characteristic_function, price_european  # noqa: E402
from rough_vol.variance import variance_swap_strike_mc  # noqa: E402

RES = ROOT / "results"
START = "<!-- validation:start (generated by scripts/validate.py, do not edit by hand) -->"
END = "<!-- validation:end -->"


def heston_logcf(u, T, kappa, theta, sigma, rho, v0):
    iu = 1j * u
    d = np.sqrt((rho * sigma * iu - kappa) ** 2 + sigma ** 2 * (iu + u ** 2))
    g = (kappa - rho * sigma * iu - d) / (kappa - rho * sigma * iu + d)
    e = np.exp(-d * T)
    C = kappa * theta / sigma ** 2 * ((kappa - rho * sigma * iu - d) * T - 2 * np.log((1 - g * e) / (1 - g)))
    D = (kappa - rho * sigma * iu - d) / sigma ** 2 * (1 - e) / (1 - g * e)
    return C + D * v0


def compute() -> dict:
    out: dict = {}
    t0 = time.time()

    mart = []
    for H, rho in [(0.05, -0.9), (0.10, -0.9), (0.30, 0.7)]:
        _, S = simulate_paths(RBergomiParams(H=H, eta=1.9, rho=rho, xi0=0.04), 50_000, 252, T=1.0, rng=7)
        ST = S[:, -1]
        mart.append({"H": H, "rho": rho, "mean_ST": float(ST.mean()), "se": float(ST.std() / np.sqrt(len(ST)))})
    out["martingale"] = mart

    k, se = variance_swap_strike_mc(RBergomiParams(H=0.10, eta=1.9, rho=-0.9, xi0=0.04), T=1.0, n_paths=50_000, rng=7)
    out["variance_swap"] = {"xi0": 0.04, "k_var": float(k), "se": float(se)}

    skew = []
    mats = np.array([0.05, 0.1, 0.2, 0.4, 0.8])
    dk = 0.02
    for H in (0.10, 0.30):
        s = implied_vol_surface(RBergomiParams(H=H, eta=1.9, rho=-0.9, xi0=0.04), strikes=np.exp([-dk, 0.0, dk]),
                                maturities=mats, n_paths=40_000, n_steps_per_year=250, rng=3)
        sk = np.abs(s[:, 2] - s[:, 0]) / (2 * dk)
        slope = float(np.polyfit(np.log(mats), np.log(sk), 1)[0])
        skew.append({"H_true": H, "slope": slope, "H_est": slope + 0.5})
    out["skew_power_law"] = skew

    p = RHestonParams(H=0.4999, lambda_=1.0, theta=0.04, rho=-0.7, nu=0.3, V0=0.04)
    errs = [abs(np.exp(characteristic_function(u, 0.5, p, 800)) - np.exp(heston_logcf(u, 0.5, 1.0, 0.04, 0.3, -0.7, 0.04)))
            for u in (1.0, 2.0, 5.0, 10.0, 20.0)]
    out["rheston_vs_heston"] = {"max_abs_cf_error": float(max(errs)), "u_grid": [1, 2, 5, 10, 20]}

    K = np.array([0.8, 0.9, 1.0, 1.1, 1.2])
    pr = price_european(RHestonParams(H=0.10, lambda_=1.0, theta=0.04, rho=-0.7, nu=0.3, V0=0.04), K=K, T=0.5,
                        n_steps=200, n_quad=128, u_max=100)
    out["rheston_prices"] = {"strikes": K.tolist(), "prices": pr.tolist(),
                             "positive": bool(np.all(pr > 0)), "decreasing": bool(np.all(np.diff(pr) < 0))}
    out["runtime_seconds"] = round(time.time() - t0)
    RES.mkdir(exist_ok=True)
    (RES / "validation.json").write_text(json.dumps(out, indent=2))
    return out


def render(v: dict) -> str:
    o = ["| Check | Expected | Result | Before the fixes in this release |", "|---|---|---|---|"]
    for m in v["martingale"]:
        o.append(f"| rBergomi E[S_T], H = {m['H']}, rho = {m['rho']} | 1 | {m['mean_ST']:.4f} (se {m['se']:.4f}) |"
                 + (" 1.83 |" if (m["H"], m["rho"]) == (0.10, -0.9) else " not measured |"))
    vs = v["variance_swap"]
    o.append(f"| rBergomi variance swap strike | xi0 = {vs['xi0']} | {vs['k_var']:.4f} (se {vs['se']:.4f}) | not measured |")
    for s in v["skew_power_law"]:
        o.append(f"| rBergomi ATM skew power law, H = {s['H_true']} | H_est near {s['H_true']} | {s['H_est']:.3f} | not measured |")
    o.append(f"| Rough Heston CF at H = 0.4999 vs closed-form Heston, u in {v['rheston_vs_heston']['u_grid']} | 0 | "
             f"max error {v['rheston_vs_heston']['max_abs_cf_error']:.1e} | 0.11 at u = 5 |")
    pr = v["rheston_prices"]
    o.append(f"| Rough Heston calls, K = 0.8 to 1.2, T = 0.5 | positive and decreasing | "
             f"{'yes' if pr['positive'] and pr['decreasing'] else 'no'} ({', '.join(f'{x:.4f}' for x in pr['prices'])}) | "
             "negative for K = 1.1 |")
    o += ["", f"All checks run in about {v['runtime_seconds']} seconds (`make validate`). Monte Carlo checks use 40,000 to 50,000 paths "
          "and 250 to 252 steps per year; the skew estimate uses finite differences at +/- 2 percent log-moneyness, so it is "
          "approximate at short maturities."]
    return "\n".join(o)


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    if "--check" in sys.argv:
        v = json.loads((RES / "validation.json").read_text())
        if pre + START + "\n" + render(v) + "\n" + END + post != text:
            sys.exit("README Validation block is out of date. Run: python scripts/validate.py")
        print("README Validation block matches results/")
        return
    v = compute()
    readme.write_text(pre + START + "\n" + render(v) + "\n" + END + post)
    print(render(v))


if __name__ == "__main__":
    main()
